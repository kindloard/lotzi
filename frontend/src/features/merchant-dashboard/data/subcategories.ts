export type ProductCategory = keyof typeof productTaxonomy;

export const productCategories = Object.keys(productTaxonomy) as ProductCategory[];

export function subcategoriesForCategory(category: string) {
  return Object.keys(categoryNode(category));
}

export function typesForSubcategory(category: string, subCategory: string) {
  const node = categoryNode(category);
  const fallbackSubCategory = Object.keys(node)[0] ?? "";
  const selected = Object.prototype.hasOwnProperty.call(node, subCategory) ? subCategory : fallbackSubCategory;
  return selected ? [...node[selected]] : [];
}

export function defaultSubcategoryForCategory(category: string) {
  return subcategoriesForCategory(category)[0] ?? "";
}

export function defaultTypeForSubcategory(category: string, subCategory: string) {
  return typesForSubcategory(category, subCategory)[0] ?? "";
}

function categoryNode(category: string) {
  return (productTaxonomy[category as ProductCategory] ?? productTaxonomy.Grocery) as Record<string, readonly string[]>;
}
